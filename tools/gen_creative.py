"""Turn fixtures/creative.json (the harness `creative` dump) into crates/items/src/creative_table.rs.

    python tools/fixtures.py creative   # writes fixtures/creative.json
    python tools/gen_creative.py        # writes the Rust table

Per item the creative tab (`getCreativeTab`), then the potion types, enchantments, spawn eggs and
fish types the sub-item rules in crates/items/src/creative.rs walk.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "fixtures" / "creative.json"
OUT = ROOT / "crates" / "items" / "src" / "creative_table.rs"

ENCH_TYPES = ["ALL", "ARMOR", "ARMOR_FEET", "ARMOR_LEGS", "ARMOR_CHEST", "ARMOR_HEAD", "WEAPON", "DIGGER",
              "FISHING_ROD", "BREAKABLE", "BOW", "WEARABLE"]


def camel(s: str) -> str:
    return "".join(p.capitalize() for p in s.lower().split("_"))


def q(s: str) -> str:
    return json.dumps(s)


def main() -> None:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    lines = [
        "//! Generated by tools/gen_creative.py from the harness `creative` dump. Do not edit.",
        "//! The creative-menu data of the 1.12.2 registries; the rules that use it are in creative.rs.",
        "",
        "use crate::creative::{EggDef, EnchDef, EnchType, Effect, PotionDef};",
        "",
        "/// `(item id, CreativeTabs index)` for every item `getCreativeTab` gives a tab, by id.",
        "#[rustfmt::skip]",
        "pub static ITEM_TABS: &[(u16, u8)] = &[",
    ]
    rows = sorted((i[0], i[2]) for i in d["items"] if i[2] >= 0)
    for k in range(0, len(rows), 8):
        lines.append("    " + " ".join(f"({a}, {b})," for a, b in rows[k:k + 8]))
    lines += ["];", "", "/// `CreativeTabs.getRelevantEnchantmentTypes()`, by tab index.", "#[rustfmt::skip]",
              "pub static TAB_ENCHANTS: [&[EnchType]; 12] = ["]
    tabs = sorted(d["tabs"])
    assert [t[0] for t in tabs] == list(range(12))
    for t in tabs:
        lines.append("    &[" + ", ".join(f"EnchType::{camel(e)}" for e in t[2]) + f"], // {t[1]}")
    lines += ["];", "", "/// `CreativeTabs.tabLabel`, by tab index (lang key `itemGroup.<label>`).",
              "pub static TAB_LABELS: [&str; 12] = [" + ", ".join(q(t[1]) for t in tabs) + "];", "",
              "/// `PotionType.REGISTRY` in id order: name, `PotionUtils.getPotionColorFromEffectList`,",
              "/// `getNamePrefixed(\"\")` and the effects (lang key, amplifier, duration, bad, instant).",
              "#[rustfmt::skip]", "pub static POTIONS: &[PotionDef] = &["]
    pots = d["potions"]
    assert [p[0] for p in pots] == list(range(len(pots))), "potion ids are not contiguous"
    for p in pots:
        effects = ", ".join(f"Effect {{ key: {q(e[0])}, amplifier: {e[1]}, duration: {e[2]}, bad: {str(bool(e[3])).lower()}, "
                            f"instant: {str(bool(e[4])).lower()} }}" for e in p[4])
        lines.append(f"    PotionDef {{ name: {q(p[1])}, color: 0x{p[2]:06x}, base: {q(p[3])}, effects: &[{effects}] }},")
    lines += ["];", "", "/// `Enchantment.REGISTRY` in id order: id, name, `getName()`, type, min and max level.",
              "#[rustfmt::skip]", "pub static ENCHANTMENTS: &[EnchDef] = &["]
    for e in d["enchantments"]:
        ty = "None" if e[3] is None else f"Some(EnchType::{camel(e[3])})"
        assert e[3] is None or e[3] in ENCH_TYPES
        lines.append(f"    EnchDef {{ id: {e[0]}, name: {q(e[1])}, key: {q(e[2])}, ty: {ty}, min: {e[4]}, max: {e[5]} }},")
    lines += ["];", "", "/// `EntityList.ENTITY_EGGS` in insertion order: entity name, `getTranslationName`, colors.",
              "#[rustfmt::skip]", "pub static EGGS: &[EggDef] = &["]
    for e in d["eggs"]:
        lines.append(f"    EggDef {{ entity: {q(e[0])}, translation: {q(e[1])}, primary: 0x{e[2]:06x}, secondary: 0x{e[3]:06x} }},")
    lines += ["];", "", "/// `ItemFishFood.FishType.values()`: metadata and `canCook()`.",
              "pub static FISH: &[(u8, bool)] = &[" + ", ".join(f"({f[0]}, {str(bool(f[2])).lower()})" for f in d["fish"]) + "];", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
