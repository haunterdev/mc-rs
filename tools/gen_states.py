"""Turn fixtures/states.json (the harness `states` dump) into crates/sim/src/states.rs.

    python tools/fixtures.py states     # writes fixtures/states.json
    python tools/gen_states.py          # writes the Rust table

Per block id: the registry path and `Block.getRenderLayer`. Per state id (block id << 4 | meta):
`getRenderType` and the property string `StateMapperBase.getPropertyString` builds (names sorted,
"" for none). A state whose `getStateFromMeta` throws is absent.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "fixtures" / "states.json"
OUT = ROOT / "crates" / "sim" / "src" / "states.rs"

RENDER = {"INVISIBLE": 1, "LIQUID": 2, "ENTITYBLOCK_ANIMATED": 3, "MODEL": 4}


def rows(values: list, per: int) -> str:
    return "\n".join("    " + " ".join(f"{v}," for v in values[i:i + per]) for i in range(0, len(values), per))


def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    names = [""] * 256
    layers = [0] * 256
    for bid, name, layer in data["blocks"]:
        names[bid] = name
        layers[bid] = layer
    render = [0] * 4096
    strings = [""]
    index = {"": 0}
    props = [0] * 4096
    for sid, rtype, pstr in data["states"]:
        render[sid] = RENDER[rtype]
        if pstr not in index:
            index[pstr] = len(strings)
            strings.append(pstr)
        props[sid] = index[pstr]
    out = [
        "//! Generated by tools/gen_states.py from the harness `states` dump (fixtures/states.json).",
        "//! Do not edit by hand. Per block: the registry path and `Block.getRenderLayer`; per state:",
        "//! `getRenderType` and the property string `StateMapperBase.getPropertyString` builds from",
        "//! `getStateFromMeta(meta).getProperties()` (names sorted, empty for none).",
        "",
        "/// `EnumBlockRenderType`; `None` for an unregistered block or a meta `getStateFromMeta` refuses.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub enum RenderType {",
        "    None,",
        "    Invisible,",
        "    Liquid,",
        "    EntityblockAnimated,",
        "    Model,",
        "}",
        "",
        "/// The registry path of a block id (`Block.REGISTRY.getNameForObject`), `None` if unregistered.",
        "pub fn block_name(block: u16) -> Option<&'static str> {",
        "    NAMES.get(block as usize).copied().filter(|n| !n.is_empty())",
        "}",
        "",
        "/// `Block.getRenderLayer` by block id: 0 SOLID, 1 CUTOUT_MIPPED, 2 CUTOUT, 3 TRANSLUCENT.",
        "pub fn render_layer(block: u16) -> u8 {",
        "    LAYERS.get(block as usize).copied().unwrap_or(0)",
        "}",
        "",
        "/// `IBlockState.getRenderType` of `getStateFromMeta`.",
        "pub fn render_type(state: u16) -> RenderType {",
        "    match RENDER.get(state as usize).copied().unwrap_or(0) {",
        "        1 => RenderType::Invisible,",
        "        2 => RenderType::Liquid,",
        "        3 => RenderType::EntityblockAnimated,",
        "        4 => RenderType::Model,",
        "        _ => RenderType::None,",
        "    }",
        "}",
        "",
        "/// The state's properties as `name=value` joined by commas, names sorted.",
        "pub fn properties(state: u16) -> &'static str {",
        "    STRINGS[STATE_PROPS.get(state as usize).copied().unwrap_or(0) as usize]",
        "}",
        "",
        "static NAMES: [&str; 256] = [",
        rows([json.dumps(n) for n in names], 8),
        "];",
        "",
        "static LAYERS: [u8; 256] = [",
        rows(layers, 32),
        "];",
        "",
        "static RENDER: [u8; 4096] = [",
        rows(render, 32),
        "];",
        "",
        f"static STRINGS: [&str; {len(strings)}] = [",
        "\n".join(f"    {json.dumps(s)}," for s in strings),
        "];",
        "",
        "static STATE_PROPS: [u16; 4096] = [",
        rows(props, 24),
        "];",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}: {sum(1 for n in names if n)} blocks, {len(strings)} property strings")


if __name__ == "__main__":
    main()
