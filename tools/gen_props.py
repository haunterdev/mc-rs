"""Turn fixtures/props.bin.gz (the harness `props` dump) into crates/worldgen/src/populate/props.rs.

    python tools/fixtures.py pop        # writes fixtures/props.bin.gz and props.json
    python tools/gen_props.py           # writes the Rust table

One u64 per state id (block id << 4 | meta):
    bits  0-5   material index (Material static-field order, see props.json)
    bits  6-19  flags (the Pop.props bit list, shifted down by 6 on read)
    bits 20-27  light opacity
    bits 28-31  light value
    bits 32-37  faces whose BlockFaceShape is SOLID, bit = EnumFacing index (D U N S W E)
    bit  38     the id is the canonical id of its state
Hardness is a separate f32 table; the sound type (`SOUND`) and particle gravity are too.
"""
from __future__ import annotations

import gzip
import json
import math
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURES = ROOT / "fixtures"
OUT = ROOT / "crates" / "worldgen" / "src" / "populate" / "props.rs"


def load(path: Path) -> dict[str, list]:
    data = gzip.decompress(path.read_bytes())
    assert data[:8] == b"MCRSFIX1", "bad magic"
    pos = 8
    out: dict[str, list] = {}
    fmt = {1: ("<i", 4), 2: ("<H", 2), 3: ("<d", 8), 4: ("<f", 4), 5: ("<q", 8)}
    while pos < len(data):
        (nlen,) = struct.unpack_from("<H", data, pos)
        pos += 2
        name = data[pos:pos + nlen].decode()
        pos += nlen
        dtype = data[pos]
        pos += 1
        (count,) = struct.unpack_from("<I", data, pos)
        pos += 4
        f, size = fmt[dtype]
        out[name] = list(struct.unpack_from("<" + f[1] * count, data, pos))
        pos += size * count
    return out


def main() -> None:
    p = load(FIXTURES / "props.bin.gz")
    meta = json.loads((FIXTURES / "props.json").read_text(encoding="utf-8"))
    materials = meta["materials"]
    sound_types = meta["sound_types"]
    packed = []
    for i in range(4096):
        mat = p["material"][i]
        assert 0 <= mat < 64
        faces = 0
        for f in range(6):
            if p["faces"][i * 6 + f] == 0:
                faces |= 1 << f
        v = (mat | p["flags"][i] << 6 | p["opacity"][i] << 20 | p["light"][i] << 28 | faces << 32
             | p["canonical"][i] << 38)
        packed.append(v)

    def row(vals: list[str]) -> str:
        if all(v == vals[0] for v in vals):
            return f"[{vals[0]}; 16]"
        return "[" + ", ".join(vals) + "]"

    def f32(x: float) -> str:
        if math.isnan(x):
            return "f32::NAN"
        return f"{x!r}" if "." in repr(x) or "e" in repr(x) else f"{x!r}.0"

    lines = [
        "//! Generated by tools/gen_props.py from the harness `props` dump. Do not edit.",
        "//! Per state id (block id << 4 | meta): material, flags, light opacity and value, solid faces.",
        "",
        "/// `Material` static fields, in declaration order.",
        "pub mod material {",
    ]
    for i, m in enumerate(materials):
        lines.append(f"    pub const {m}: u8 = {i};")
    lines += ["}", "", "#[rustfmt::skip]", "pub static PROPS: [[u64; 16]; 256] = ["]
    for b in range(256):
        lines.append(f"    {row([f'0x{v:x}' for v in packed[b * 16:b * 16 + 16]])},")
    lines += ["];", "", "/// `IBlockState.getBlockHardness`; NaN where the harness could not read it.",
              "#[rustfmt::skip]", "pub static HARDNESS: [[f32; 16]; 256] = ["]
    for b in range(256):
        lines.append(f"    {row([f32(x) for x in p['hardness'][b * 16:b * 16 + 16]])},")
    lines += ["];", "", "/// `SoundType` static fields, in declaration order.", "pub mod sound_type {"]
    for i, t in enumerate(sound_types):
        lines.append(f"    pub const {t}: u8 = {i};")
    lines += ["}", "", "/// `Block.getSoundType`, a `sound_type` index.", "#[rustfmt::skip]",
              "pub static SOUND: [[u8; 16]; 256] = ["]
    for b in range(256):
        vals = p["sound"][b * 16:b * 16 + 16]
        assert all(0 <= v < len(sound_types) for v in vals)
        lines.append(f"    {row([str(v) for v in vals])},")
    lines += ["];", "", "/// `Block.blockParticleGravity`, per block id.", "#[rustfmt::skip]",
              "pub static PARTICLE_GRAVITY: [f32; 256] = ["]
    grav = [f32(p["particle_gravity"][b * 16]) for b in range(256)]
    for b in range(0, 256, 16):
        lines.append("    " + ", ".join(grav[b:b + 16]) + ",")
    lines += ["];", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
